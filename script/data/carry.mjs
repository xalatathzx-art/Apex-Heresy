/**
 * Сколько персонаж может нести, поднять и толкать.
 *
 * Таблица 9-33 (Rogue Trader, стр. 269; та же таблица стоит и в Dark Heresy).
 * Строку выбирает сумма бонусов Силы и Стойкости.
 *
 * В системе до сих пор считался только первый столбец — предел переноски. Два
 * других книга печатает прямо на листе персонажа, и без них лист неполон.
 */

/** [переноска, подъём, толкание] в килограммах, по сумме SB + TB от 0 до 20. */
const TABLE = Object.freeze([
    [0.9, 2.25, 4.5],
    [2.25, 4.5, 9],
    [4.5, 9, 18],
    [9, 18, 36],
    [18, 36, 72],
    [27, 54, 108],
    [36, 72, 144],
    [45, 90, 180],
    [56, 112, 225],
    [67, 135, 270],
    [78, 157, 315],
    [90, 180, 360],
    [112, 225, 450],
    [225, 450, 900],
    [337, 675, 1350],
    [450, 900, 1800],
    [675, 1350, 2700],
    [900, 1800, 3600],
    [1350, 2700, 5400],
    [1800, 3600, 7200],
    [2250, 4500, 9000]
]);

/**
 * Пределы переноски для суммы бонусов.
 *
 * Сумма ниже нуля читается как ноль, выше двадцати — как двадцать: таблица
 * кончается, а персонаж — нет.
 *
 * @param {number} bonusSum сумма бонусов Силы и Стойкости
 * @returns {{carry: number, lift: number, push: number}}
 */
export function carryingLimits(bonusSum) {
    const index = Math.min(Math.max(Math.floor(Number(bonusSum) || 0), 0), TABLE.length - 1);
    const [carry, lift, push] = TABLE[index];
    return {carry, lift, push};
}

/**
 * Прыжки, как их печатает лист персонажа (стр. 399).
 *
 * Прыжок в длину с места равен бонусу Силы в метрах (стр. 268); прыжок вверх —
 * двадцать сантиметров на бонус. Это базовые значения: броски Ловкости в бою их
 * удлиняют, но на листе стоят именно они.
 *
 * @param {number} strengthBonus
 * @returns {{leap: number, jump: number}} в метрах
 */
export function baseLeapAndJump(strengthBonus) {
    const bonus = Math.max(Number(strengthBonus) || 0, 0);
    return {leap: bonus, jump: bonus * 0.2};
}
